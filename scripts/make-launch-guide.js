const fa = (s) => String(s).replace(/\d/g, (d) => '۰۱۲۳۴۵۶۷۸۹'[+d])

const run = (text, o = {}) => new TextRun({ text, rightToLeft: true, font: { ascii: FONT, hAnsi: FONT, cs: FONT, eastAsia: FONT }, ...o })
// متن با **پررنگ**
const runs = (text, o = {}) => text.split(/(\*\*[^*]+\*\*)/).filter(Boolean).map((t) =>
  t.startsWith('**') ? run(t.slice(2, -2), { ...o, bold: true, boldComplexScript: true }) : run(t, o))

const P = (text, o = {}) => new Paragraph({ bidirectional: true, alignment: AlignmentType.START, spacing: { after: 120, line: 360 }, ...o, children: typeof text === 'string' ? runs(text) : text })
const H1 = (text) => new Paragraph({ heading: HeadingLevel.HEADING_1, bidirectional: true, pageBreakBefore: true, spacing: { before: 0, after: 200 }, children: [run(text)] })
const H2 = (text) => new Paragraph({ heading: HeadingLevel.HEADING_2, bidirectional: true, spacing: { before: 300, after: 120 }, keepNext: true, children: [run(text)] })
const H3 = (text) => new Paragraph({ heading: HeadingLevel.HEADING_3, bidirectional: true, spacing: { before: 200, after: 80 }, keepNext: true, children: [run(text)] })
const Bullet = (text) => new Paragraph({ bidirectional: true, numbering: { reference: 'bullets', level: 0 }, spacing: { after: 60, line: 340 }, children: runs(text) })
const Check = (text) => new Paragraph({ bidirectional: true, indent: { start: 360 }, spacing: { after: 70, line: 340 }, children: [run('☐  ', { color: BLUE, size: 24 }), ...runs(text)] })
const Done = (text) => new Paragraph({ bidirectional: true, indent: { start: 360 }, spacing: { after: 70, line: 340 }, children: [run('✔  ', { color: '1F9D55', bold: true }), ...runs(text)] })

// جعبهٔ نکته (پاراگراف با سایه و خط کناری)
const Note = (title, lines, fill = TINT, bar = BLUE) => lines.map((l, i) => new Paragraph({
  bidirectional: true, shading: { type: ShadingType.CLEAR, fill, color: 'auto' },
  border: { right: { style: BorderStyle.SINGLE, size: 18, color: bar, space: 8 } },
  indent: { start: 120, end: 120 }, spacing: { after: i === lines.length - 1 ? 200 : 0, before: i === 0 ? 120 : 0, line: 340 },
  children: i === 0 && title ? [run(title + ' ', { bold: true, boldComplexScript: true, color: bar }), ...runs(l)] : runs(l),
}))

// قدم شماره‌دار
const Step = (n, title, desc) => [
  new Paragraph({ bidirectional: true, keepNext: true, spacing: { before: 260, after: 80 },
    children: [run(`قدم ${fa(n)}  `, { bold: true, boldComplexScript: true, color: 'FFFFFF', shading: { type: ShadingType.CLEAR, fill: BLUE, color: 'auto' }, size: 22 }),
      run('  ' + title, { bold: true, boldComplexScript: true, size: 26, sizeComplexScript: 26, color: INK })] }),
  ...(desc ? [P(desc, { spacing: { after: 80, line: 340 } })] : []),
]

// جدول راست‌به‌چپ با عرض‌های DXA
const TABLE_W = 9638 // عرض متن A4 با حاشیهٔ ۲ سانت
const Tbl = (headers, rows, ratios) => {
  const sum = ratios.reduce((a, b) => a + b, 0)
  const widths = ratios.map((r) => Math.floor((r / sum) * TABLE_W))
  widths[widths.length - 1] += TABLE_W - widths.reduce((a, b) => a + b, 0)
  const border = { style: BorderStyle.SINGLE, size: 4, color: LINE }
  const cell = (text, w, head, fill) => new TableCell({
    width: { size: w, type: WidthType.DXA }, margins: { top: 80, bottom: 80, left: 110, right: 110 },
    shading: { type: ShadingType.CLEAR, fill: head ? BLUE : fill ?? 'FFFFFF', color: 'auto' },
    borders: { top: border, bottom: border, left: border, right: border },
    children: String(text).split('\n').map((t) => new Paragraph({ bidirectional: true, spacing: { after: 0, line: 300 },
      children: runs(t, head ? { bold: true, boldComplexScript: true, color: 'FFFFFF', size: 20, sizeComplexScript: 20 } : { size: 20, sizeComplexScript: 20 }) })),
  })
  return new Table({
    visuallyRightToLeft: true, width: { size: TABLE_W, type: WidthType.DXA }, columnWidths: widths,
    rows: [
      new TableRow({ tableHeader: true, children: headers.map((h, i) => cell(h, widths[i], true)) }),
      ...rows.map((r, ri) => new TableRow({ cantSplit: true, children: r.map((c, i) => cell(c, widths[i], false, ri % 2 ? 'F7F9FC' : 'FFFFFF')) })),
    ],
  })
}
